package kr.co.mbn.trot.ai.provider;

/**
 * 질문 의도. 어떤 서비스에서 근거를 끌어올지 결정합니다.
 *
 * <p>의도 분류에 별도 LLM 호출을 쓰지 않습니다. 도메인이 좁아서 키워드 매칭으로 충분하고,
 * 왕복이 한 번 줄어 응답이 빨라집니다.
 */
public enum Intent {
    /** 일정·콘서트·방송 시간 */
    SCHEDULE,
    /** 기사·영상 추천 */
    CONTENT,
    /** 팬 모임 참여 */
    GATHERING,
    /** 성지순례 장소 */
    PLACE,
    /** 투표·스밍 등 팬 활동 가이드 */
    TIP,
    /** 이 앱 자체에 대한 질문(기능·사용법·어디서 하나요). 근거는 기능 카탈로그입니다. */
    SERVICE,
    /** 스타·플랫폼 전반. 근거를 폭넓게 모읍니다. */
    GENERAL,
    /** 답변 범위 밖 — LLM 을 호출하지 않고 거절합니다. */
    OUT_OF_SCOPE
}
